/**
 * Dedicated AJAX endpoint for Sparky Course Curriculum & Study Material Management
 */

// Disable all display errors to prevent JSON output corruption
@ini_set('display_errors', '0');
@ini_set('upload_max_filesize', '1024M');
@ini_set('post_max_size', '1024M');
@ini_set('max_execution_time', '0');
@ini_set('max_input_time', '-1');
@ini_set('memory_limit', '1024M');
error_reporting(0);

// Start output buffer immediately
ob_start();

// Prevent session-course mismatch in local.inc.php
unset($_GET['id_session'], $_POST['id_session'], $_REQUEST['id_session'], $_SESSION['id_session'], $_SESSION['session_name']);

$cidReset = true;
require_once __DIR__.'/../global.inc.php';
require_once __DIR__.'/../lib/course_curriculum.lib.php';

// Discard any buffer generated by global.inc.php
while (ob_get_level()) {
    ob_end_clean();
}

header('Content-Type: application/json; charset=utf-8');

// Catch payload exceeding POST limit
if ($_SERVER['REQUEST_METHOD'] === 'POST' && empty($_POST) && empty($_FILES) && isset($_SERVER['CONTENT_LENGTH']) && (int)$_SERVER['CONTENT_LENGTH'] > 0) {
    echo json_encode([
        'success' => false,
        'error' => 'The uploaded file exceeds the server maximum upload limit (1024 MB).'
    ]);
    exit;
}

$action = isset($_REQUEST['action']) ? trim($_REQUEST['action']) : '';
$courseCode = isset($_REQUEST['code']) ? trim($_REQUEST['code']) : (isset($_REQUEST['course_code']) ? trim($_REQUEST['course_code']) : '');

if (empty($courseCode)) {
    $firstCourse = CourseManager::get_courses_list();
    if (!empty($firstCourse)) {
        $courseCode = $firstCourse[0]['code'];
    }
}

$currentUserId = api_get_user_id();

// Verify access permissions
$isAllowed = api_is_platform_admin() || api_is_platform_admin_by_id() || api_is_course_admin() || CourseManager::is_course_teacher($currentUserId, $courseCode) || ($currentUserId > 0 && CourseManager::is_user_subscribed_in_course($currentUserId, $courseCode));

if (!$isAllowed && $currentUserId <= 0) {
    echo json_encode([
        'success' => false,
        'error' => 'Your session has expired. Please refresh the page and log in again.'
    ]);
    exit;
}

CourseCurriculum::initTables();

// 1. UPLOAD LESSON MEDIA (Video, PDF, Study Material, Audio)
if ($action === 'ajax_upload_lesson_media' || $action === 'upload_media') {
    $lessonId = isset($_REQUEST['lesson_id']) ? (int)$_REQUEST['lesson_id'] : 0;
    
    // Check files array
    $uploadedFile = null;
    $inputName = '';
    foreach (['file', 'video_file', 'pdf_file', 'doc_file', 'audio_file', 'media_file'] as $k) {
        if (isset($_FILES[$k])) {
            $inputName = $k;
            if ($_FILES[$k]['error'] === UPLOAD_ERR_OK) {
                $uploadedFile = $_FILES[$k];
                break;
            } else {
                $err = $_FILES[$k]['error'];
                $errMap = [
                    UPLOAD_ERR_INI_SIZE => 'File is too large for server configuration (upload_max_filesize).',
                    UPLOAD_ERR_FORM_SIZE => 'File exceeds HTML form limit.',
                    UPLOAD_ERR_PARTIAL => 'The file was only partially uploaded.',
                    UPLOAD_ERR_NO_FILE => 'No file was uploaded.',
                    UPLOAD_ERR_NO_TMP_DIR => 'Missing temporary upload directory on server.',
                    UPLOAD_ERR_CANT_WRITE => 'Failed to write file to disk.',
                    UPLOAD_ERR_EXTENSION => 'A PHP extension stopped the file upload.'
                ];
                $errMsg = isset($errMap[$err]) ? $errMap[$err] : ('Upload error code ' . $err);
                echo json_encode(['success' => false, 'error' => $errMsg]);
                exit;
            }
        }
    }

    if (!$uploadedFile) {
        echo json_encode(['success' => false, 'error' => 'No file was received in the request. Please choose a file.']);
        exit;
    }

    $lesson = CourseCurriculum::getLesson($lessonId);
    $lTitle = $lesson ? $lesson['title'] : $uploadedFile['name'];

    $uploadRes = CourseCurriculum::handleUploadedFile($uploadedFile, $courseCode, $lTitle);
    if (!$uploadRes) {
        echo json_encode(['success' => false, 'error' => 'Failed to save uploaded file into curriculum storage directory.']);
        exit;
    }

    // Update lesson record if valid lesson ID
    if ($lessonId > 0) {
        CourseCurriculum::saveLesson($lessonId, [
            'content_url' => $uploadRes['web_url'],
            'file_path' => $uploadRes['rel_path'],
            'file_size' => $uploadRes['file_size'],
            'mime_type' => $uploadRes['mime_type'],
            'lesson_type' => $uploadRes['lesson_type']
        ]);
    }

    echo json_encode([
        'success' => true,
        'url' => $uploadRes['web_url'],
        'file_name' => $uploadRes['original_name'],
        'file_size' => $uploadRes['file_size'],
        'mime_type' => $uploadRes['mime_type'],
        'lesson_type' => $uploadRes['lesson_type']
    ]);
    exit;
}

// 2. GET LESSON DATA
if ($action === 'ajax_get_lesson') {
    $lessonId = isset($_REQUEST['id']) ? (int)$_REQUEST['id'] : 0;
    $lesson = CourseCurriculum::getLesson($lessonId);
    if (!$lesson) {
        echo json_encode(['error' => 'Lesson not found']);
        exit;
    }
    echo json_encode($lesson);
    exit;
}

// 3. DELETE CHAPTER
if ($action === 'ajax_delete_chapter') {
    $chapterId = isset($_REQUEST['id']) ? (int)$_REQUEST['id'] : 0;
    if ($chapterId > 0) {
        CourseCurriculum::deleteChapter($chapterId);
        echo json_encode(['success' => true, 'message' => 'Chapter and lessons deleted successfully.']);
    } else {
        echo json_encode(['success' => false, 'error' => 'Invalid chapter ID.']);
    }
    exit;
}

// 4. DELETE LESSON
if ($action === 'ajax_delete_lesson') {
    $lessonId = isset($_REQUEST['id']) ? (int)$_REQUEST['id'] : 0;
    if ($lessonId > 0) {
        CourseCurriculum::deleteLesson($lessonId);
        echo json_encode(['success' => true, 'message' => 'Lesson deleted successfully.']);
    } else {
        echo json_encode(['success' => false, 'error' => 'Invalid lesson ID.']);
    }
    exit;
}

echo json_encode(['success' => false, 'error' => 'Unknown action: ' . htmlspecialchars($action)]);
exit;